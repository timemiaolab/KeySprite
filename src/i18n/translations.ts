export function resolveTranslations(language: LanguageCode): TranslationStrings {
  const primary = TRANSLATIONS[language];
  const fallback = TRANSLATIONS.en;
  const base = TRANSLATIONS['zh-CN'];
  const source = primary ?? fallback;
  const resolved = { ...source };
  for (const key of Object.keys(base) as (keyof TranslationStrings)[]) {
    if (!resolved[key]) {
      resolved[key] = fallback[key] || base[key];
    }
  }
  return resolved;
}
